# 3. reboot, or a stalled wire
# ---------------------------------------------------------------------------

class Recorder:
    """Stands in for the terminal, so what was said can be asserted on."""

    def __init__(self):
        self.lines = []

    def line(self, kind, text):
        self.lines.append((kind, text))

    def said(self, needle):
        return any(needle in text for _, text in self.lines)


class Clock:
    def __init__(self):
        self.t = 1000.0

    def __call__(self):
        return self.t


def watch():
    rec = Recorder()
    clock = Clock()
    return monitor.Watch(rec, clock=clock), rec, clock


def check_reboot():
    w, rec, clock = watch()

    w.frame({'t': 'hello', 'boot_id': 'aaaa1111', 'reset': 'POWERON', 'fw': '0.11.0'})
    for i in range(4):
        clock.t += 0.25
        w.frame({'t': 'beat', 'uptime_s': 0.5 + i * 0.25, 'boot_id': 'aaaa1111'})
    ok('one boot while the board keeps reporting', len(w.boots) == 1, len(w.boots))

    # Gone for four seconds, and back with an uptime shorter than the gap. That
    # is the signature of a restart and nothing else produces it.
    clock.t += 4.0
    w.tick()
    ok('silence is put on the record', rec.said('no telemetry'))

    w.frame({'t': 'hello', 'boot_id': 'bbbb2222', 'reset': 'BROWNOUT', 'fw': '0.11.0'})
    ok('a fresh boot_id is a second boot', len(w.boots) == 2, len(w.boots))
    ok('and the reset reason is carried through', w.boots[1]['reset'] == 'BROWNOUT')
    ok('the previous boot is recorded with how long it lasted',
       abs(w.boots[0]['lasted'] - 1.25) < 1e-9, w.boots[0]['lasted'])

    w.summary()
    ok('the summary states it was a restart', rec.said('It is not a transmit stall'))
    ok('and names the reason', rec.said('BROWNOUT'))


def check_reboot_without_hello():
    """A missed identity frame must not lose a boot."""
    w, rec, clock = watch()

    w.frame({'t': 'hello', 'boot_id': 'aaaa1111', 'reset': 'POWERON'})
    clock.t += 0.25
    w.frame({'t': 'beat', 'uptime_s': 8.0, 'boot_id': 'aaaa1111'})
    clock.t += 0.25
    w.frame({'t': 'beat', 'uptime_s': 0.4, 'boot_id': 'aaaa1111'})

    ok('uptime going backwards is a boot even with no hello', len(w.boots) == 2, len(w.boots))
    ok('and it says how it was noticed', rec.said('uptime went backwards'))


def check_stall():
    """The other half of the question, and the answer that is easy to miss."""
    w, rec, clock = watch()

    w.frame({'t': 'hello', 'boot_id': 'aaaa1111', 'reset': 'POWERON'})
    clock.t += 0.25
    w.frame({'t': 'beat', 'uptime_s': 10.0, 'boot_id': 'aaaa1111'})

    clock.t += 4.0
    w.tick()
    # Back with an uptime that ran straight through the gap. The board never
    # stopped; something between it and here did.
    w.frame({'t': 'beat', 'uptime_s': 14.0, 'boot_id': 'aaaa1111'})

    ok('a gap the uptime ran through is not a boot', len(w.boots) == 1, len(w.boots))
    ok('and it is named as a stall', rec.said('the transmit path stalled'))

    w.summary()
    ok('the summary refuses to call it a restart',
       rec.said('uptime never went backwards') and not rec.said('It is not a transmit stall'))


def check_attached_mid_session():
    """
    A board already running announces itself every five seconds, so the first
    frame the monitor sees is usually a beat.
    """
    w, rec, clock = watch()

    clock.t += 0.25
    w.frame({'t': 'beat', 'uptime_s': 402.5, 'boot_id': 'cccc3333'})
    ok('a beat before any hello still registers the boot', len(w.boots) == 1, len(w.boots))
    ok('and no reset reason is invented for it', w.boots[0]['reset'] is None)
    ok('the banner says how the boot was noticed', rec.said('attached mid-session'))

    clock.t += 0.25
    w.frame({'t': 'beat', 'uptime_s': 402.75, 'boot_id': 'cccc3333'})
    w.summary()
    ok('and the summary counts one boot, not two', rec.said('1 boot,'))


def check_beats_without_a_boot_id():
    """Older firmware, or a frame shape this build has never seen."""
    w, rec, clock = watch()

    clock.t += 0.25
    w.frame({'t': 'beat', 'uptime_s': 12.0})
    w.summary()
    ok('beats with no boot_id are not counted as a boot', len(w.boots) == 0, len(w.boots))
    ok('and the summary declines to answer rather than guessing',
       rec.said('nothing here can tell a restart from a stall'))
    ok('it does not claim one boot it never saw', not rec.said('One boot, uptime never'))


def check_says_nothing_it_did_not_see():
    """Absence is drawn, not hidden — the rule the rest of the project follows."""
    w, rec, _ = watch()
    w.summary()
    ok('a board that said nothing is reported as exactly that',
       rec.said('No beats arrived at all'))
    ok('and no verdict is offered about why',
       not rec.said('transmit path') and not rec.said('restarted'))


# ---------------------------------------------------------------------------

print('\n  monitor\n')
check_against_spec()
check_line_reader()
check_reboot()
check_reboot_without_hello()
check_stall()
check_attached_mid_session()
check_beats_without_a_boot_id()
check_says_nothing_it_did_not_see()

print('\n  %d passed, %d failed%s\n'
      % (passed, failed, ', %d skipped' % skipped if skipped else ''))
sys.exit(1 if failed else 0)
