# 2. the line bound
# ---------------------------------------------------------------------------

def check_line_reader():
    r = monitor.LineReader()
    ok('a line split across reads is assembled once',
       r.push('#OHW1 par') == [] and r.push('t\nrest') == ['#OHW1 part'])

    r = monitor.LineReader()
    ok('carriage returns do not survive', r.push('one\r\ntwo\r\n') == ['one', 'two'])
    ok('and empty lines are not passed on', monitor.LineReader().push('\n\n\na\n') == ['a'])

    # One bad line costs one bad line. The frames queued behind it must still
    # arrive, or a single burst of noise would take a whole image with it.
    r = monitor.LineReader(limit=32)
    r.push('x' * 40)
    ok('an overlong line is counted', r.dropped == 1, r.dropped)
    got = r.push('tail-of-the-bad-line\nkept\n')
    ok('its remainder is discarded and the reader resynchronises', got == ['kept'], got)
    ok('and the buffer did not keep growing', len(r.buf) == 0, len(r.buf))

    r = monitor.LineReader()
    r.push('half a line with no newline')
    r.reset()
    ok('a board leaving the bus takes its half-line with it', r.push('whole\n') == ['whole'])


