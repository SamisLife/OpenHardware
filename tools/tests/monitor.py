"""
tests for tools/monitor.py.

    python tools/tests/monitor.py

Three things are checked, and the first is the reason this file exists.

THE THIRD IMPLEMENTATION HAS TO AGREE WITH THE FIRST
    monitor.py decodes OHW1 for the third time in this repository — after
    protocol.js, which is the specification, and hw_proto.c, which is what the
    board runs. Three independent copies are deliberate, and the deal is that
    the CRC catches a divergence immediately. That is only true if somebody
    checks, so the vectors below are generated by running the real encoder out
    of protocol.js rather than written down here. Frames copied into this file
    by hand would prove that monitor.py agrees with whoever typed them.

THE RULES WITH NO HARDWARE BEHIND THEM
    The line bound and the boot accounting are ordinary code. A rule that can
    only be exercised with a board attached is one nobody exercises, which is
    how the monitor would come to be trusted without ever having been right.

THE VERDICT IS THE PRODUCT
    Telling a board that restarted from a board that went quiet is the whole
    job. It is worth more than one assertion.
"""

import importlib.util
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
PROTOCOL_JS = ROOT / 'frontend' / 'js' / 'link' / 'protocol.js'

spec = importlib.util.spec_from_file_location('monitor', ROOT / 'tools' / 'monitor.py')
monitor = importlib.util.module_from_spec(spec)
spec.loader.exec_module(monitor)

passed = failed = skipped = 0


def ok(name, cond, detail=''):
    global passed, failed
    if cond:
        passed += 1
        print('  PASS  ' + name)
    else:
        failed += 1
        print('  FAIL  ' + name + (('  — ' + str(detail)) if detail else ''))


def skip(name, why):
    global skipped
    skipped += 1
    print('  SKIP  %s — %s' % (name, why))


# ---------------------------------------------------------------------------
# 1. agreement with the specification
# ---------------------------------------------------------------------------

# Every case is a shape the wire actually carries, plus the three that have
# caught real divergences before: a payload containing the frame terminator, a
# payload outside ASCII, and a chunk at full width.
CASES = """
[
  { "t": "hello", "proto": 1, "fw": "0.11.0", "sha": "e8bcc63f9260f958",
    "slot": "factory", "board": "esp32s3_generic", "mac": "3C:84:27:AB:CD:EF",
    "boot_id": "5abc1234", "reset": "BROWNOUT", "provisioned": false, "ssid": "",
    "psram": 8388608, "flash": 8388608, "heap": 300000, "heap_total": 390000,
    "temp_crit_c": 85, "rx": 0, "temp_c": 32.5 },
  { "t": "beat", "uptime_s": 12.75, "heap_free": 299184, "psram_free": 8380416,
    "psram_largest": 8257536, "cpu_mhz": 240, "boot_id": "5abc1234" },
  { "t": "status", "stage": "camera_absent", "detail": "ESP_ERR_NOT_SUPPORTED" },
  { "t": "status", "stage": "quoted", "detail": "a literal \\" *ABCD\\" inside a string" },
  { "t": "status", "stage": "wide", "detail": "32.5 \\u00b0C on the die, ss\\u00efd \\u00e9\\u00e8" },
  { "t": "img", "seq": 7, "w": 800, "h": 600, "q": 12, "bytes": 4096, "chunks": 9 },
  { "t": "ping" }
]
"""

GENERATOR = """
import { encodeFrame, crc16 } from %s;
const cases = JSON.parse(%s);
console.log(JSON.stringify({
  frames: cases.map(c => ({ obj: c, line: encodeFrame(c).replace(/\\n$/, '') })),
  malformed: (() => { const b = '{"t":"ping",}';
    return `#OHW1 ${b} *${crc16(b).toString(16).toUpperCase().padStart(4, '0')}`; })(),
}));
"""


def vectors():
    """
    Framed lines produced by the real encoder, or None if node is absent.

    The cases travel inside the script rather than as an argument, and the
    script is pure ASCII because json.dumps escapes everything above it. A
    Windows console hands argv to a child in the active code page, which
    replaces every character the page cannot represent — so the degree sign
    that this check exists to exercise would arrive as a question mark and the
    two implementations would be compared on a payload neither would ever see.
    """
    script = GENERATOR % (json.dumps(PROTOCOL_JS.as_uri()), json.dumps(CASES))
    try:
        out = subprocess.run(
            [_node(), '--input-type=module', '-e', script],
            capture_output=True, encoding='utf-8', timeout=60)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if out.returncode != 0:
        return None
    return json.loads(out.stdout)


def _node():
    return 'node.exe' if sys.platform == 'win32' else 'node'


def check_against_spec():
    # The published check value, first. A CRC that fails this is wrong in a way
    # no round-trip against another implementation would reveal, because both
    # could be wrong together.
    ok('crc16("123456789") is 0x29B1', monitor.crc16(b'123456789') == 0x29B1,
       hex(monitor.crc16(b'123456789')))

    v = vectors()
    if v is None:
        skip('frames from protocol.js round-trip',
             'node is not available, so the specification could not be run')
        return

    for case in v['frames']:
        frame, reason = monitor.decode_line(case['line'])
        ok('round-trips a %s frame' % case['obj']['t'],
           frame == case['obj'] and reason is None, (frame, reason))

    # Length is checked separately: a generator that silently produced nothing
    # would otherwise pass this section by asserting nothing at all.
    ok('every case was exercised', len(v['frames']) == 7, len(v['frames']))

    line = v['frames'][0]['line']
    ok('a corrupted body fails its CRC',
       monitor.decode_line(line[:20] + 'x' + line[21:])[1] == 'crc')
    ok('a frame with no CRC suffix is refused',
       monitor.decode_line(line[:line.rfind(' *')])[1] == 'no-crc-suffix')
    ok('a valid CRC over malformed JSON is reported as JSON, not corruption',
       monitor.decode_line(v['malformed'])[1] == 'json')

    # The property the sentinel exists for. ESP-IDF log output shares this
    # endpoint, and mistaking it for a damaged frame would report a fault on
    # every boot.
    frame, reason = monitor.decode_line('I (312) harness: openhardware 0.11.0')
    ok('log output is neither a frame nor an error', frame is None and reason is None, reason)


